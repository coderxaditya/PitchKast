/**
 * Pre-renders the dotted world map and the arc geometry.
 *
 * Why this exists, in numbers measured on a fast laptop:
 *
 *   new DottedMap(...)   1223 ms   — a synchronous main-thread block
 *   getSVG(...)             4 ms   — 578KB of markup
 *   inline as a data URI          — 942KB, because percent-encoding inflates it
 *   the same SVG as a file        —  24KB over the wire, gzipped
 *
 * Doing that work in the browser put 942KB of encoded SVG into the middle of
 * the page's HTML — 80% of a 1.2MB document — so everything after it arrived
 * late, and then cost another second of blocked main thread on hydration. On a
 * phone that second is closer to five.
 *
 * Run after changing anything in `countries.ts`:
 *
 *   node scripts/build-world-map.mjs
 *
 * It reads that file directly, so the coordinates have one source. The
 * component checks the generated arc count against the live list and fails the
 * build if they disagree, so a forgotten run cannot ship silently.
 */
import DottedMapImport from "dotted-map";
import { mkdir, writeFile } from "node:fs/promises";

import { ARCS } from "../components/reach/countries.ts";

const DottedMap = DottedMapImport.default ?? DottedMapImport;

const SVG_OUT = "public/map/world-dots.svg";
const TS_OUT = "components/reach/projected.ts";

const map = new DottedMap({ height: 100, grid: "diagonal" });

/* The dark cut. White at 25% is what makes the landmasses read as a dotted
   relief rather than a grey smear, and the background matches the band's own
   Gray 900 exactly so the mask can fade the map into it with no seam. */
const svg = map.getSVG({
  radius: 0.22,
  color: "#FFFFFF40",
  shape: "circle",
  backgroundColor: "#111827",
});

await mkdir("public/map", { recursive: true });
await writeFile(SVG_OUT, svg);

/** The library's own projection. A hand-rolled equirectangular formula is out
    by about 9% of the map's height, which is enough to put central India in the
    Bay of Bengal. */
const project = ({ lat, lng }) => {
  const pin = map.getPin({ lat, lng });
  return { x: +pin.x.toFixed(2), y: +pin.y.toFixed(2) };
};

const arcs = ARCS.map((arc) => ({
  start: project(arc.start),
  end: project(arc.end),
  label: arc.end.label ?? "",
}));

const body = `/**
 * GENERATED by \`scripts/build-world-map.mjs\` — do not edit by hand.
 *
 * Arc endpoints projected into the dotted map's own coordinate space, so the
 * browser never has to build the map to know where a pin goes. Re-run the
 * script after changing \`countries.ts\`.
 */

export type MapPoint = { x: number; y: number };

/** Matches the generated SVG. The overlay shares it so no conversion is needed. */
export const MAP_VIEWBOX = "0 0 198 100";
export const MAP_SRC = "/map/world-dots.svg";

export const ARC_POINTS: { start: MapPoint; end: MapPoint; label: string }[] =
${JSON.stringify(arcs, null, 2)
  .split("\n")
  .map((line) => (line ? "  " + line : line))
  .join("\n")
  .trimStart()};
`;

await writeFile(TS_OUT, body);

console.log(
  `wrote ${SVG_OUT} (${(svg.length / 1024).toFixed(0)}KB) and ${TS_OUT} (${arcs.length} arcs)`,
);
